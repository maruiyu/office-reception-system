"use client";

import Link from "next/link";
import { usePathname, useRouter } from "next/navigation";
import { supabase } from "@/lib/supabase";

const NAV_ITEMS = [
  { href: "/admin", label: "ダッシュボード", icon: "home" },
  { href: "/admin/staff", label: "スタッフ管理", icon: "users" },
  { href: "/admin/departments", label: "部署管理", icon: "building" },
  { href: "/admin/codes", label: "受付番号発行", icon: "key" },
  { href: "/admin/logs", label: "来訪ログ", icon: "list" },
  { href: "/admin/settings", label: "システム設定", icon: "settings" },
];

